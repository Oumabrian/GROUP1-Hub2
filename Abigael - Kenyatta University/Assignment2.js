//Ask the user to enter a color
let color = prompt("Enter a color(either red,blue or green): ");

// Check if the color is red, blue or green using if/switch statements
switch (color) {
    case "red":
        console.log("You picked red.");
        break;
    case "blue":
        console.log("You picked blue.");
        break;
        case "green":
            console.log("You picked green.");
            break;
    default:
        console.log("I don't know that color.");
}

